import { _electron } from 'playwright';
import { readFile, writeFile, mkdtemp, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';

const { executable } = JSON.parse(await readFile('artifacts/packaged-app.json', 'utf8'));
const directory = await mkdtemp(path.join(tmpdir(), 'umg-c2pa-app-'));
const unsigned = path.join(directory, 'Example audio.wav');
const samples = 24000, bytes = Buffer.alloc(44 + samples * 2);
bytes.write('RIFF'); bytes.writeUInt32LE(bytes.length - 8, 4); bytes.write('WAVEfmt ', 8); bytes.writeUInt32LE(16, 16);
bytes.writeUInt16LE(1, 20); bytes.writeUInt16LE(1, 22); bytes.writeUInt32LE(48000, 24); bytes.writeUInt32LE(96000, 28);
bytes.writeUInt16LE(2, 32); bytes.writeUInt16LE(16, 34); bytes.write('data', 36); bytes.writeUInt32LE(samples * 2, 40);
for (let i = 0; i < samples; i++) bytes.writeInt16LE(Math.round(Math.sin(i * .03) * 6500), 44 + i * 2);
await writeFile(unsigned, bytes); await mkdir('artifacts/ui', { recursive: true });
const electron = await _electron.launch({ executablePath: executable, env: { ...process.env, ELECTRON_ENABLE_LOGGING: '1' }, timeout: 30000 });
try {
  const page = await electron.firstWindow();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('#choose-audio').waitFor();
  await page.screenshot({ path: 'artifacts/ui/intake.png', fullPage: true });
  await page.locator('#tab-credentials').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#tab-how').getAttribute('aria-selected'), 'true');
  assert.match(await page.locator('#how-panel').textContent(), /@contentauth\/c2pa-node/);
  assert.match(await page.locator('#how-panel').textContent(), /Rust core/);
  await page.screenshot({ path: 'artifacts/ui/how-it-works.png', fullPage: true });
  await page.locator('#tab-credentials').click();
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  assert.equal(await page.locator('#test-mode').isChecked(), false);
  await page.locator('#file-input').setInputFiles(unsigned);
  await page.waitForFunction(() => document.getElementById('validation-summary').textContent.includes('No embedded'), { timeout: 30000 });
  assert.equal(await page.locator('.check-state').allTextContents().then(a => a.join(',')), 'N/A,N/A,N/A');
  await page.waitForFunction(() => document.getElementById('audio').readyState >= 1);
  const checksBeforeGuide = await page.locator('.check-state').allTextContents();
  await page.locator('#tab-how').click();
  await page.locator('#tab-credentials').click();
  assert.deepEqual(await page.locator('.check-state').allTextContents(), checksBeforeGuide);
  await page.locator('#test-mode').check();
  await page.waitForFunction(() => document.querySelector('[data-check=trust] .check-state').textContent === 'N/A');
  assert.equal(await page.locator('#mode-badge').isVisible(), true);
  await page.locator('#test-mode').uncheck();
  await page.waitForFunction(() => document.querySelector('[data-check=trust] .check-state').textContent === 'N/A');
  await page.locator('#tab-ai').click(); await page.locator('#simulate-ai').click();
  await page.locator('#ai-result:not([hidden])').waitFor();
  assert.match(await page.locator('#ai-result').textContent(), /Simulated result/);
  assert.match(await page.locator('#ai-result').textContent(), /no audio analysis was performed/);
  await page.screenshot({ path: 'artifacts/ui/simulation.png', fullPage: true });
  await page.locator('#tab-ddex').click(); assert.match(await page.locator('#ddex-panel').textContent(), /No DDEX package is parsed/);
  await page.locator('#tab-credentials').click();
  if (process.env.C2PA_TEST_ASSET) {
    await page.locator('#file-input').setInputFiles(process.env.C2PA_TEST_ASSET);
    await page.waitForFunction(() => document.querySelector('[data-check=signature] .check-state').textContent === 'PASS', { timeout: 30000 });
    assert.equal(await page.locator('[data-check=trust] .check-state').textContent(), 'FAIL');
    await page.locator('#test-mode').check();
    await page.waitForFunction(() => document.querySelector('[data-check=trust] .check-state').textContent.includes('TEST MODE'), { timeout: 30000 });
    await page.waitForFunction(() => document.querySelectorAll('#provenance-graph g[role=button]').length > 1);
    await page.screenshot({ path: 'artifacts/ui/local-signed-test-mode.png', fullPage: true });
    await page.locator('#expand-graph').click(); await page.locator('#close-graph').waitFor();
    const before = await page.locator('#graph-zoom').textContent(); await page.locator('#zoom-in').click();
    assert.notEqual(await page.locator('#graph-zoom').textContent(), before);
    await page.locator('#fit-graph').click();
    await page.screenshot({ path: 'artifacts/ui/local-signed-graph.png', fullPage: true });
    await page.locator('#close-graph').click(); await page.locator('#raw-button').click();
    assert.equal(await page.locator('#details-dialog').evaluate(e => e.open), true);
    await page.keyboard.press('Escape');
    await page.locator('#test-mode').uncheck();
    await page.waitForFunction(() => document.querySelector('[data-check=trust] .check-state').textContent === 'FAIL');
  }
  await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 760));
  await page.locator('#tab-how').click();
  await page.screenshot({ path: 'artifacts/ui/local-how-minimum-width.png', fullPage: true });
  assert.ok(await page.locator('.reader-flow').evaluate(el => [...el.querySelectorAll('li > code')].every(code => code.scrollWidth <= code.clientWidth + 1)));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log('Packaged Mac app: ingest, SDK inspection, preview metadata, renderer isolation, How it works navigation, simulation, DDEX and unsigned Test Mode passed.');
  console.log(process.env.C2PA_TEST_ASSET ? 'Supplied signed asset: default/test trust, raw manifest and graph interactions passed.'
    : 'Signed-asset trust and graph interactions skipped: C2PA_TEST_ASSET is unset.');
} finally { await electron.close(); }
